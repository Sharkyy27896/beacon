$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Set-Location $root

$dotnet = Join-Path $root '.tools\dotnet\dotnet.exe'
$wix = Join-Path $root '.tools\wix6\wix.exe'
$publishDir = Join-Path $root 'publish\Beacon'
$filesWxs = Join-Path $root 'installer\Files.wxs'
$output = Join-Path $root 'Beacon-Setup.msi'

# Always republish: an existing publish folder may contain binaries from an
# older source revision, which would silently ship stale code in the MSI.
& $dotnet publish (Join-Path $root 'src\Beacon\Beacon.csproj') -c Release -r win-x64 --self-contained true -o $publishDir --nologo
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed with exit code $LASTEXITCODE" }

$files = Get-ChildItem -Path $publishDir -File | Sort-Object Name
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<!-- Generated by tools/build_installer.ps1. Do not edit by hand. -->')
[void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
[void]$sb.AppendLine('  <Fragment>')
[void]$sb.AppendLine('    <ComponentGroup Id="BeaconFiles" Directory="INSTALLFOLDER">')
$i = 0
foreach ($file in $files) {
    $i++
    # Keep paths repository-relative so the source tree never leaks a local
    # user profile path. WiX resolves Source from the current working directory
    # (the repo root, set above), not from this .wxs file's folder.
    $relative = $file.FullName.Substring($root.Length + 1)
    $source = $relative.Replace('&', '&amp;').Replace('"', '&quot;')
    [void]$sb.AppendLine(('        <Component Id="c{0}" Guid="*">' -f $i))
    [void]$sb.AppendLine(('          <File Id="f{0}" Source="{1}" KeyPath="yes" />' -f $i, $source))
    [void]$sb.AppendLine('        </Component>')
}
[void]$sb.AppendLine('    </ComponentGroup>')
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')
Set-Content -Path $filesWxs -Value $sb.ToString() -Encoding UTF8

& $wix build (Join-Path $root 'installer\Product.wxs') $filesWxs -arch x64 -out $output
if ($LASTEXITCODE -ne 0) { throw "WiX build failed with exit code $LASTEXITCODE" }

Get-Item $output | Select-Object FullName, Length
